MAX_DRONES = 8

DEFAULTS = {
    'num_drones': 2,
    'world_name': 'dave_ocean_waves',
    'polygon_x': [0.0, 40.0, 40.0, 0.0],
    'polygon_y': [0.0, 0.0, 30.0, 30.0],
    'spawn': {'x': 0.0, 'y': 0.0, 'z': -75.0, 'yaw': 1.5708, 'spacing_y': 6.0},
    'survey': {'altitude': 5.0, 'fov_deg': 90.0, 'lane_overlap': 0.5,
               'step_length': 1.5, 'descent_rate': 0.4, 'max_z_vel': 0.4,
               'sonar_max_range': 30.0, 'output_root': '/tmp/bluerov_survey_images'},
    'timing': {'spawn_delay': 30.0, 'survey_delay': 45.0},
    'drone1_teleop': True,
    # shared_edges: every drone sweeps the whole polygon, side by side, aligning to its
    #               neighbour's live edge; strips: fixed strip per drone (no talking)
    'fleet_mode': 'shared_edges',
}


def _merge(base, over):
    out = copy.deepcopy(base)
    for k, v in (over or {}).items():
        out[k] = _merge(out[k], v) if isinstance(v, dict) and isinstance(out.get(k), dict) else v
    return out


def load_config(path=None):
    import yaml
    over = {}
    if path and os.path.exists(path):
        with open(path) as f:
            over = yaml.safe_load(f) or {}
    elif path:
        print(f'[fleet] config file {path} not found -- using built-in defaults')
    cfg = _merge(DEFAULTS, over)
    n = int(cfg['num_drones'])
    if not 1 <= n <= MAX_DRONES:
        raise ValueError(f'num_drones must be 1..{MAX_DRONES}, got {n}')
    cfg['num_drones'] = n
    if cfg['fleet_mode'] not in ('shared_edges', 'strips'):
        raise ValueError("fleet_mode must be 'shared_edges' or 'strips'")
    if len(cfg['polygon_x']) != len(cfg['polygon_y']) or len(cfg['polygon_x']) < 3:
        raise ValueError('polygon_x and polygon_y must be the same length (>= 3 points)')
    lanes = lane_count(cfg)
    if n > lanes:
        print(f'[fleet] num_drones={n} but this polygon only has about {lanes} sweep lane(s) '
              f'at {cfg["survey"]["altitude"]} m altitude -- using {lanes} drone(s)')
        cfg['num_drones'] = lanes
    return cfg


def lane_count(cfg):
    """Roughly how many sweeps the polygon needs (lanes run along Y, side by side in X).
    Drones beyond this number would have nothing to do."""
    s = cfg['survey']
    swath = 2.0 * s['altitude'] * math.tan(math.radians(s['fov_deg']) / 2.0)
    width = max(cfg['polygon_x']) - min(cfg['polygon_x'])
    if width <= swath:
        return 1
    return 1 + int(math.ceil((width - swath) / (swath - s['lane_overlap']) - 1e-9))


def build_fleet(cfg):
    sp = cfg['spawn']
    fleet = []
    for k in range(1, cfg['num_drones'] + 1):
        i = k - 1
        fleet.append(dict(
            index=k,
            name=f'drone{k}',                            # ROS namespace / folder name
            model='bluerov2' if k == 1 else f'bluerov2_{k}',   # DAVE namespace == Gazebo model
            mavros='/mavros' if k == 1 else f'/drone{k}',
            instance=i,                                  # ArduSub SITL instance
            sysid=k,
            offset=(0.0, i * sp['spacing_y']),           # spawn relative to drone 1
            spawn=dict(x=sp['x'], y=sp['y'] + i * sp['spacing_y'], z=sp['z'], yaw=sp['yaw']),
        ))
    return fleet


