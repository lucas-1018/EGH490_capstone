def _model_sdf_for(src_text, d):
    s = src_text
    s = s.replace('<model name="bluerov2">', f'<model name="{d["model"]}">')
    s = s.replace('<topic>/model/bluerov2/', f'<topic>/model/{d["model"]}/')
    s = s.replace('<cmd_topic>/model/bluerov2/', f'<cmd_topic>/model/{d["model"]}/')
    s = s.replace('<namespace>bluerov2</namespace>', f'<namespace>{d["model"]}</namespace>')
    s, n = re.subn(r'<fdm_port_in>\d+</fdm_port_in>',
                   f'<fdm_port_in>{9002 + 10 * d["instance"]}</fdm_port_in>', s)
    if n != 1:
        raise RuntimeError('could not find <fdm_port_in> in the bluerov2 model.sdf')
    return s


def write_drone_files(share, d):
    """Create <share>/description/<model>/ and <share>/config/<model>/ for drone d."""
    m = d['model']
    src_desc = os.path.join(share, 'description', 'bluerov2')
    src_cfg = os.path.join(share, 'config', 'bluerov2')
    desc = os.path.join(share, 'description', m)
    cfg = os.path.join(share, 'config', m)
    os.makedirs(desc, exist_ok=True)
    os.makedirs(cfg, exist_ok=True)
    with open(os.path.join(src_desc, 'model.sdf')) as f:
        sdf = _model_sdf_for(f.read(), d)
    with open(os.path.join(desc, 'model.sdf'), 'w') as f:
        f.write(sdf)
    with open(os.path.join(src_desc, 'model.config')) as f:
        mc = f.read().replace('<name>bluerov2</name>', f'<name>{m}</name>')
    with open(os.path.join(desc, 'model.config'), 'w') as f:
        f.write(mc)
    with open(os.path.join(src_cfg, 'ardusub.parm')) as f:
        parm = re.sub(r'(?m)^SYSID_THISMAV.*\n?', '', f.read()).rstrip('\n')
    with open(os.path.join(cfg, 'ardusub.parm'), 'w') as f:
        f.write(parm + f'\nSYSID_THISMAV    {d["sysid"]}\n')
    rc = (ROBOT_CONFIG_TEMPLATE.replace('__MODEL__', m)
          .replace('__INSTANCE__', str(d['instance']))
          .replace('__MAVROS_NS__', d['name'])
          .replace('__SYSID__', str(d['sysid'])))
    with open(os.path.join(cfg, 'robot_config.py'), 'w') as f:
        f.write(rc)


def remove_drone_files(share, d):
    for sub in ('description', 'config'):
        shutil.rmtree(os.path.join(share, sub, d['model']), ignore_errors=True)
