def survey_strips(cfg, fleet):
    from .polygon_split import split_by_lanes
    s = cfg['survey']
    pitch = 2.0 * s['altitude'] * math.tan(math.radians(s['fov_deg']) / 2.0) - s['lane_overlap']
    return split_by_lanes(cfg['polygon_x'], cfg['polygon_y'], len(fleet), pitch)


